# Ensure this matches your backend URL
API_URL = "http://127.0.0.1:8000/submit-ticket"

user_input = st.text_area("Customer Ticket:", height=150, placeholder="E.g., My laptop screen is broken, is it covered under warranty?")

if st.button("Execute Multi-Agent Workflow", type="primary"):
    if user_input.strip() == "":
        st.warning("⚠️ Please enter a ticket message first.")
    else:
        final_response = None  # Veliya oru empty variable create panrom
        
        # UI UX: Show fake processing steps inside the status box
        with st.status("Initializing AI Agents...", expanded=True) as status:
            st.write("🔗 Connecting to API...")
            time.sleep(0.5)
            st.write("🔍 [Agent: Triage] Analyzing user sentiment and intent...")
            time.sleep(1)
            st.write("📚 [Agent: Retrieval] Fetching policy context...")
            time.sleep(1)
            st.write("🧠 [Agent: Resolution] Drafting final response...")
            
            try:
                # Actual API Call
                response = requests.post(API_URL, json={"message": user_input})
                
                if response.status_code == 200:
                    status.update(label="Workflow Complete!", state="complete", expanded=False)
                    data = response.json()
                    final_response = data.get("response", "No response generated.")
                else:
                    status.update(label="Workflow Failed", state="error")
                    st.error(f"Server Error {response.status_code}: {response.text}")
                    
            except requests.exceptions.ConnectionError:
                status.update(label="Connection Failed", state="error")
                st.error("🚨 Connection Refused: Ensure the FastAPI backend is running on http://127.0.0.1:8000")

        # ==========================================
        # 🔥 OUTSIDE THE STATUS BLOCK 🔥
        # ==========================================
        if final_response:
            st.divider() 
            st.subheader("🎯 AI Generated Resolution")
            with st.container(border=True):
                st.markdown(final_response)
            st.caption("✨ Generated by Nexus Multi-Agent RAG System")