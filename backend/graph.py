from langgraph.graph import StateGraph, END
from backend.model import TicketState
from backend.agents import triage_agent, retrieval_agent, resolution_agent

def build_graph():
    workflow = StateGraph(TicketState)
    workflow.add_node("triage", triage_agent)
    workflow.add_node("retrieval", retrieval_agent)
    workflow.add_node("resolution", resolution_agent)
    workflow.set_entry_point("triage")
    workflow.add_edge("triage", "retrieval")
    workflow.add_edge("retrieval", "resolution")
    workflow.add_edge("resolution", END)
    return workflow.compile()

support_ai_app = build_graph()

def process_ticket(message: str) -> str:
    print(f"\n🚀 --- NEW TICKET RECEIVED --- \nMessage: {message}")
    initial_state = {"message": message, "category": "", "context": "", "response": ""}
    
    try:
        final_state = support_ai_app.invoke(initial_state)
        print(f"✅ --- GRAPH EXECUTION COMPLETE ---")
        return final_state.get("response", "Error: No response generated by graph.")
    except Exception as e:
        print(f"❌ --- ERROR --- {str(e)}")
        return f"AI Processing Error: {str(e)}"